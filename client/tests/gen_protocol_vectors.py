"""Writes ProtocolVectors.h from the server's protocol.py, so the C++ client is
checked byte for byte against the Python implementation."""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent.parent / "server"))

import protocol as p

CLIENT_ID = bytes(range(16))
PUBLIC_KEY = bytes(i % 256 for i in range(160))
ENCRYPTED_KEY = bytes((i * 7) % 256 for i in range(128))


def request(code, payload):
    return p.REQUEST_HEADER.pack(CLIENT_ID, p.CLIENT_VERSION, code, len(payload)) + payload


VECTORS = {
    "REGISTER_REQUEST": request(p.RequestCode.REGISTER, p.encode_name("Ayala")),
    "PUBLIC_KEY_REQUEST": request(p.RequestCode.PUBLIC_KEY, p.encode_name("Ayala") + PUBLIC_KEY),
    "RECONNECT_REQUEST": request(p.RequestCode.RECONNECT, p.encode_name("Ayala")),
    "CRC_OK_REQUEST": request(p.RequestCode.CRC_OK, p.encode_name("data.bin")),
    "FILE_PACKET_HEADER": p.FILE_PACKET_HEADER.pack(0x00019010, 102400, 1, 2, p.encode_name("data.bin")),
    "REGISTER_OK_RESPONSE": p.build_response(p.ResponseCode.REGISTER_OK, p.client_id_payload(CLIENT_ID)),
    "AES_KEY_RESPONSE": p.build_response(p.ResponseCode.AES_KEY,
                                         p.aes_key_payload(CLIENT_ID, ENCRYPTED_KEY)),
    "FILE_RECEIVED_RESPONSE": p.build_response(
        p.ResponseCode.FILE_RECEIVED,
        p.file_received_payload(CLIENT_ID, 0x00019010, "data.bin", 0xDEADBEEF)),
    "GENERAL_ERROR_RESPONSE": p.build_response(p.ResponseCode.GENERAL_ERROR),
}


def main():
    lines = ["#pragma once", "", "// generated by gen_protocol_vectors.py - do not edit", "",
             "namespace vectors {", ""]
    for name, data in VECTORS.items():
        lines.append(f'inline constexpr const char* {name} =\n    "{data.hex()}";')
    lines += ["", "}", ""]
    (HERE / "ProtocolVectors.h").write_text("\n".join(lines), encoding="ascii")


if __name__ == "__main__":
    main()
